await call(path,{type:'release',groupId:group.id},{ticket:first.token});
await call(path,{type:'claim',groupId:other.id},{h5:true,ticket:second.token});
await call(path,{type:'move',groupId:other.id,seq:1,dx:170,dy:90},{h5:true,ticket:second.token});
