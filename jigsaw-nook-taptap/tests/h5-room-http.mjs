async function raw(path,body,options={}) {
 const base=options.h5?h5:web;
 const headers={Origin:options.h5?source:web,'CF-Connecting-IP':'127.0.0.1',...(options.h5?{'X-Jigsaw-H5-Session':options.session||session}:{Cookie:options.cookie||cookie}),...(options.ticket?{Authorization:'Bearer '+options.ticket}:{}),...(body!==undefined&&!(body instanceof FormData)?{'Content-Type':'application/json'}:{})};
 return fetch(base+(options.h5?'/h5':'')+path,{method:body===undefined?'GET':'POST',headers,body:body===undefined?undefined:body instanceof FormData?body:JSON.stringify(body)});
}
async function call(path,body,options={}) {const response=await raw(path,body,options),data=await response.json();assert.ok(response.ok,JSON.stringify({path,status:response.status,data}));return {response,data};}
